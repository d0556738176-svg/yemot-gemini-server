// Extensions 1 and 3 (owner, 19.11): a question ABOUT what the system can do
// is answered, not carried out. "Do you download only from YouTube?" has the
// word YouTube and the word download, but he is asking, not ordering: no
// search, no download, no hand-off. Used by every keyword shortcut (the brain's
// rules, the whole-web hand-off) before it acts on a word.

const ASKING = /(?:^|\s)(?:האם|למה|מדוע|איך|כיצד|מאיפה|מאיזה|מאילו|מאיזו|באיזה|באילו|באיזו|איזה|אילו|איזו|כמה|מה ה?הבדל|מה אתה|מה את|מה המערכת)(?=\s)/u;
const ABILITY = /(?:(?:אתה|את|אתם|המערכת|השלוחה|השלוחות|הבוט|המנוע|זה)\s+)?(?:יכול|יכולה|יכולים|מסוגל|מסוגלת|יודע|יודעת|מוריד|מורידה|מורידים|משמיע|משמיעה|מחפש|מחפשת|תומך|תומכת|עובד|עובדת|שומר|שומרת|מקבל|מקבלת)(?=$|[\s?,.!])/u;
const ONLY_FROM = /(?:רק\s+(?:מ|ב)(?:יוטיוב|אתר|האתר|אינטרנט|גוגל)|(?:מ|ב)(?:איזה|אילו)\s+(?:אתרים|אתר|מקורות|מקומות)|מאיפה\s+(?:אתה|את)\s+(?:מוריד|מורידה|מביא|מביאה|לוקח|לוקחת))/u;
const SELF = /(?:אתה|את|המערכת|השלוחה|הבוט)(?=$|[\s?,.!])/u;
// A real request names what to act on: "תוכל להוריד לי את השיר אדון עולם".
const NAMED_OBJECT = /(?:לי\s+)?את\s+(?:ה)?(?:שיר|סרטון|קליפ|הקלטה|שיעור|פרק|סט|קובץ|זה|הזה|הזאת|אותו)?\s*[֐-׿a-zA-Z0-9]{2,}/u;

export function isCapabilityQuestion(text) {
  const t = String(text || '').replace(/[״"׳]/g, '').replace(/\s+/g, ' ').trim();
  if (!t) return false;
  if (ONLY_FROM.test(t)) return true;
  const asks = ASKING.test(' ' + t) || /\?\s*$/.test(t);
  if (!asks || !ABILITY.test(t)) return false;
  // "Can you download for me the song X" asks him to act: not a capability question.
  if (NAMED_OBJECT.test(t) && !/(?:האם|למה|מדוע|מאיזה|מאילו|באיזה|באילו|באיזו|איזה אתרים|אילו אתרים|רק מ)/u.test(t)) return false;
  return SELF.test(t) || /^(?:האם|למה|מדוע|איך|מאיפה|מאיזה|מאילו|באיזה|באילו|באיזו)\s/u.test(t);
}

